function requisites(s) {
  const d = data(s);
  const rows = [
    ['Наименование', d.name], ['ИНН', s.op_inn], ['ОГРНИП', s.op_ogrnip], ['ОКПО', s.op_okpo], ['ОКТМО', s.op_oktmo],
    ['Рег. № ПФР', s.op_pfr], ['Адрес регистрации', s.op_address], ['Адрес клуба', d.clubAddress],
    ['Телефон клуба', s.phone], ['E-mail', s.op_email],
  ];
  if (s.show_bank) {
    rows.push(['Расчётный счёт', s.bank_account], ['Банк', s.bank_name], ['БИК', s.bank_bik], ['Корр. счёт', s.bank_corr]);
  }
  return { title: 'Реквизиты', rows: rows.filter((r) => r[1]) };
}

